'''Cheat Sheet: Todos los métodos de String
lower(): Pasa todo a minúsculas.
upper(): Pasa todo a mayúsculas.
capitalize(): Primera letra del string en mayúscula, el resto minúsculas.
title(): Primera letra de cada palabra en mayúscula.
swapcase(): Intercambia mayúsculas por minúsculas y viceversa.
strip(): Elimina espacios (o caracteres) al principio y al final.
lstrip(): Elimina espacios solo a la izquierda.
rstrip(): Elimina espacios solo a la derecha.
split(sep): Divide el string en una lista usando un separador (por defecto el espacio).
join(lista): Une los elementos de una lista en un solo string usando la cadena como unión.
replace(viejo, nuevo): Reemplaza un texto por otro.
find(sub): Devuelve el índice de la primera vez que aparece el texto (devuelve -1 si no lo halla).
index(sub): Igual que find, pero da error si no lo encuentra.
count(sub): Cuenta cuántas veces aparece un texto dentro del string.
startswith(sub): Devuelve True si el string empieza con ese texto.
endswith(sub): Devuelve True si el string termina con ese texto.
isalpha(): True si todos los caracteres son letras.
isdigit(): True si todos los caracteres son números.
isalnum(): True si es una mezcla de letras y números (sin símbolos).
islower(): True si todo está en minúsculas.
isupper(): True si todo está en mayúsculas.
isspace(): True si el string solo contiene espacios en blanco.
len(string): (Función) Devuelve la cantidad total de caracteres.'''